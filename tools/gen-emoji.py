#!/usr/bin/env python3
"""
Generates docs/emoji.js — the dashboard's emoji picker data — from Unicode's
official emoji-test.txt (UTS #51).

    curl -O https://unicode.org/Public/emoji/latest/emoji-test.txt
    python3 tools/gen-emoji.py emoji-test.txt

Skin-tone variants are left out on purpose: they multiply the grid by six
without adding a distinct emoji, and a reaction role only needs the base.
The source file is never committed; this output is.
"""
import json
import pathlib
import re
import sys

SKIN = re.compile(r'\b(light|medium-light|medium|medium-dark|dark) skin tone\b')
OUT = pathlib.Path(__file__).resolve().parent.parent / 'docs' / 'emoji.js'


def main():
    if len(sys.argv) < 2:
        sys.exit('usage: gen-emoji.py <path to emoji-test.txt>')
    groups, group, kept, skipped = [], None, 0, 0
    for line in pathlib.Path(sys.argv[1]).read_text(encoding='utf-8').splitlines():
        if line.startswith('# group:'):
            group = line.split(':', 1)[1].strip()
            if group != 'Component':
                groups.append([group, []])
            continue
        if not line or line.startswith('#') or 'fully-qualified' not in line:
            continue
        if group == 'Component':
            continue
        m = re.search(r'#\s+(\S+)\s+E\d+\.\d+\s+(.+)$', line)
        if not m:
            continue
        char, name = m.group(1), m.group(2).strip()
        if SKIN.search(name):
            skipped += 1
            continue
        groups[-1][1].append([char, name])
        kept += 1

    groups = [g for g in groups if g[1]]
    OUT.write_text(
        '/* Generated by tools/gen-emoji.py from Unicode emoji-test.txt — do not edit. */\n'
        'window.EMOJI_DATA = ' + json.dumps(groups, ensure_ascii=False, separators=(',', ':')) + ';\n',
        encoding='utf-8')
    print(f'{OUT}: {kept} emoji in {len(groups)} groups ({skipped} skin-tone variants skipped), '
          f'{OUT.stat().st_size // 1024} KB')


if __name__ == '__main__':
    main()
